import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../',import.meta.url);
const policy=(await readFile(new URL('src/client-policy.js',base),'utf8')).replace(/^export /gm,'');
const source=await readFile(new URL('src/client-ui.js',base),'utf8');
if(!source.includes('/* ORBAT_CLIENT_POLICY */'))throw new Error('Missing client policy insertion point');
const bundle='// Generated by pnpm run build; edit src/client-ui.js and src/client-policy.js.\n'+source.replace('/* ORBAT_CLIENT_POLICY */',policy);
await writeFile(new URL('client.js',base),bundle,'utf8');
console.log('Built DSH Client artifact with shared, tested collaboration policies.');
