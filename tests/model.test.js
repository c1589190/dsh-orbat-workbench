test('stats aggregates personnel, equipment and node count recursively', () => {
  const result = stats(sampleTree());
  assert.equal(result.personnel, 210);
  assert.equal(result.personnelMax, 260);
  assert.deepEqual(result.equipment, { 步枪: 70, 步战车: 10, 火炮: 2 });
  assert.equal(result.equipTotal, 82);
  assert.equal(result.nodes, 3);
});

test('stats on a leaf and equipment with countMax', () => {
  const result = stats(unit({
    personnel: 0,
    personnelMax: 0,
    equipment: [{ name: '机枪', count: 2, countMax: 4 }],
  }));
  const { personnel, personnelMax, equipment, equipTotal, nodes } = result;
  assert.deepEqual(
    { personnel, personnelMax, equipment, equipTotal, nodes },
    {
      personnel: 0,
      personnelMax: 0,
      equipment: { 机枪: 2 },
      equipTotal: 2,
      nodes: 1,
    },
  );
  assert.deepEqual(result.coverage, {
    personnel: { known: 0, unknown: 0, estimated: 0, legacyAmbiguous: 1 },
    equipment: {
      known: { 机枪: 2 },
      knownTotal: 2,
      unknown: 0,
      estimated: 0,
      legacyAmbiguous: 0,
    },
  });
});

test('normalizeRoot clones, strips external ids and supplies defaults', () => {
  const input = unit({
    id: 'external-root',
    children: [unit({ id: 'external-child', name: '子单位' })],
    custom: { note: '保留' },
  });
  const before = JSON.stringify(input);
  const normalized = normalizeRoot(input);
  assert.equal(JSON.stringify(input), before);
  assert.notEqual(normalized.id, 'external-root');
  assert.notEqual(normalized.children[0].id, 'external-child');
  assert.notEqual(normalized.id, normalized.children[0].id);
  assert.equal(normalized.children[0].name, '子单位');
  assert.equal(normalized.layout, 'h');
  assert.equal(normalized.customName, false);
  assert.equal(normalized.collapsed, false);
  assert.equal(normalized.stack, false);
  assert.equal(normalized.remark, '');
  assert.equal(normalized.mod, '');
  assert.deepEqual(normalized.custom, { note: '保留' });
  normalized.custom.note = '改';
  assert.equal(input.custom.note, '保留');
});

test('normalizeRoot treats inputs as untrusted and generates a fresh id each time', () => {
  const first = normalizeRoot(unit());
  const second = normalizeRoot(unit());
  assert.notEqual(first.id, second.id);
  assert.match(first.id, /^n_/);
});

test('validateRoot reports node count and maximum depth without requiring ids', () => {
  const result = validateRoot(sampleTree());
  assert.deepEqual(result, { ok: true, nodes: 3, depth: 3 });
});

test('validateRoot can require persisted internal ids', () => {
  assert.throws(() => validateRoot(unit(), { requireIds: true }), errCode('invalid_id'));
  const normalized = normalizeRoot(unit());
  assert.equal(validateRoot(normalized, { requireIds: true }).ok, true);
});

test('duplicate ids are rejected', () => {
  const root = unit({
    children: [unit({ id: 'same' }), unit({ id: 'same' })],
  });
  assert.throws(() => normalizeRoot(root), errCode('duplicate_id'));
});

test('depth boundary is exactly MAX_DEPTH', () => {
  assert.equal(validateRoot(chain(MAX_DEPTH)).depth, MAX_DEPTH);
  assert.throws(() => validateRoot(chain(MAX_DEPTH + 1)), errCode('depth_exceeded'));
});

test('node boundary is exactly MAX_NODES', () => {
  const children = Array.from({ length: MAX_NODES - 1 }, (_, index) =>
    unit({ name: `节点${index}` }));
  const root = unit({ children });
  assert.equal(validateRoot(root).nodes, MAX_NODES);
  root.children.push(unit({ name: '超出' }));
  assert.throws(() => validateRoot(root), errCode('node_limit_exceeded'));
});

test('invalid scalar values are rejected instead of coerced', () => {
  const cases = [
    [{ type: 'bogus' }, 'invalid_type'],
    [{ type: '' }, 'invalid_type'],
    [{ echelon: 'bogus' }, 'invalid_echelon'],
    [{ layout: 'bogus' }, 'invalid_layout'],
    [{ layout: 'auto' }, 'invalid_layout'],
    [{ layout: 'horizontal' }, 'invalid_layout'],
    [{ children: {} }, 'invalid_children'],
    [{ children: null }, 'invalid_children'],
    [{ personnel: '10' }, 'invalid_number'],
    [{ personnel: -1 }, 'invalid_number'],
    [{ personnel: 1.5 }, 'invalid_number'],
    [{ personnelMax: NaN }, 'invalid_number'],
    [{ equipment: 'rifle' }, 'invalid_equipment'],
    [{ equipment: [{ name: '枪', count: '2' }] }, 'invalid_number'],
    [{ equipment: [{ name: '枪', count: -2 }] }, 'invalid_number'],
    [{ equipment: [{ name: '枪', count: 1.2 }] }, 'invalid_number'],
    [{ equipment: [{ name: '', count: 1 }] }, 'invalid_equipment'],
    [{ customName: 'yes' }, 'invalid_boolean'],
    [{ collapsed: 0 }, 'invalid_boolean'],
    [{ stack: 'no' }, 'invalid_boolean'],
    [{ name: 123 }, 'invalid_text'],
    [{ remark: {} }, 'invalid_text'],
    [{ mod: [] }, 'invalid_text'],
  ];
  for (const [patch, code] of cases) {
    assert.throws(() => normalizeRoot(unit(patch)), errCode(code), JSON.stringify(patch));
  }
});

test('non-object nodes and malformed customs are rejected', () => {
  assert.throws(() => normalizeRoot(null), errCode('invalid_node'));
  assert.throws(() => normalizeRoot([]), errCode('invalid_node'));
  assert.throws(() => normalizeRoot('tree'), errCode('invalid_node'));
  assert.throws(() => normalizeRoot(unit({ custom: { bad: Number.NaN } })), errCode('invalid_custom'));
  const circular = {};
  circular.self = circular;
  assert.throws(() => normalizeRoot(unit({ custom: circular })), errCode('invalid_custom'));
});

test('prototype-polluting keys are rejected everywhere', () => {
  const protoNode = JSON.parse(
    '{"name":"x","type":"infantry","echelon":"army","__proto__":{"polluted":true}}');
  assert.throws(() => normalizeRoot(protoNode), errCode('forbidden_key'));
  const protoCustom = unit({ custom: JSON.parse('{"__proto__":{"polluted":true}}') });
  assert.throws(() => normalizeRoot(protoCustom), errCode('forbidden_key'));
  assert.equal({}.polluted, undefined);
});

test('layout defaults follow the upstream vertical-echelon set', () => {
  const vertical = new Set(['platoon', 'section', 'squad', 'team', 'individual']);
  for (const echelon of ECHELONS) {
    const normalized = normalizeRoot(unit({ echelon }));
    assert.equal(normalized.layout, vertical.has(echelon) ? 'v' : 'h', echelon);
  }
  assert.equal(normalizeRoot(unit({ echelon: 'squad', layout: 'h' })).layout, 'h');
  assert.equal(normalizeRoot(unit({ echelon: 'brigade', layout: 'v' })).layout, 'v');
});

test('upstream-shaped nodes keep exact types, badge, stack and custom:null', () => {
  const upstream = {
    type: 'signal',
    echelon: 'team',
    name: '师直属通讯火力组',
    customName: false,
    remark: '',
    children: [],
    collapsed: false,
    layout: 'v',
    personnel: 0,
    personnelMax: 0,
    equipment: [{ name: '通信车', count: 2 }],
    custom: null,
    mod: '',
    badge: 'data:image/png;base64,AA',
    stack: true,
  };
  const normalized = normalizeRoot(upstream);
  assert.equal(normalized.type, 'signal');
  assert.equal(TYPE_LABELS[normalized.type], '通讯');
  assert.equal(normalized.echelon, 'team');
  assert.equal(normalized.layout, 'v');
  assert.equal(normalized.badge, 'data:image/png;base64,AA');
  assert.equal(normalized.stack, true);
  assert.equal(Object.hasOwn(normalized, 'custom'), true);
  assert.equal(normalized.custom, null);
  assert.equal(stats(normalized).nodes, 1);
});


test('unknown node and equipment fields are preserved rather than dropped', () => {
  const normalized = normalizeRoot(unit({
    origin: 'upstream',
    extra: { note: '保留', nested: [1, null, 'x'] },
    equipment: [{ name: '枪', count: 2, make: '自制', note: null }],
  }));
  assert.equal(normalized.origin, 'upstream');
  assert.deepEqual(normalized.extra, { note: '保留', nested: [1, null, 'x'] });
  assert.equal(normalized.equipment[0].make, '自制');
  assert.equal(normalized.equipment[0].note, null);
  const roundTrip = normalizeRoot(normalized);
  assert.equal(roundTrip.origin, 'upstream');
  assert.equal(roundTrip.equipment[0].make, '自制');
});
